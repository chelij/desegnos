//! `commands.txt` is the one command list. Tauri rejects a command at runtime unless the
//! permission manifest knows it, so the generated permission files must match the list exactly.
use std::{collections::BTreeSet, fs};

fn names(list: &str) -> BTreeSet<String> {
    list.lines()
        .filter(|line| !line.trim().is_empty())
        .map(|line| line.trim().rsplit("::").next().unwrap().to_owned())
        .collect()
}

#[test]
fn permission_files_match_the_command_list() {
    let listed = names(include_str!("../commands.txt"));
    assert!(!listed.is_empty(), "commands.txt must declare commands");
    let generated: BTreeSet<String> = fs::read_dir(concat!(env!("CARGO_MANIFEST_DIR"), "/permissions/autogenerated"))
        .unwrap()
        .filter_map(|entry| entry.unwrap().file_name().to_str()?.strip_suffix(".toml").map(str::to_owned))
        .collect();
    assert_eq!(listed, generated, "permissions/autogenerated is out of step with commands.txt");
}
